import Foundation

/// Turns a preset into a self-contained iTerm2 Python API script.
///
/// The preset is embedded as JSON and interpreted by a small fixed runner, so the
/// script stays readable and hand-editable, and no user text is spliced into code.
/// The runner only ever creates windows, tabs and splits — it never closes anything.
enum ScriptGenerator {
    static let presetIDMarker = "# iTermPresets-id: "

    static func python(for preset: Preset) -> String {
        let data = PresetPayload(preset)
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        // JSON escapes every `"` inside strings, so `"""` can never appear in it.
        let json = String(decoding: (try? encoder.encode(data)) ?? Data("{}".utf8), as: UTF8.self)

        return """
        #!/usr/bin/env python3
        # Generated by iTermPresets — preset "\(preset.name.replacingOccurrences(of: "\n", with: " "))".
        \(presetIDMarker)\(preset.id.uuidString)
        #
        # Opens new tabs/splits only. It never closes or changes anything already open.
        # Run it from iTerm's Scripts menu, or edit the PRESET data below by hand.

        import json
        import os

        import iterm2

        PRESET = json.loads(r\"\"\"
        \(json)
        \"\"\")


        def hex_to_color(value):
            value = value.lstrip("#")
            return iterm2.Color(int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16))


        def customizations(tab, pane):
            profile = iterm2.LocalWriteOnlyProfile()
            directory = pane.get("directory") or tab.get("directory")
            if directory:
                profile.set_initial_directory_mode(
                    iterm2.InitialWorkingDirectory.INITIAL_WORKING_DIRECTORY_CUSTOM)
                profile.set_custom_directory(os.path.expanduser(directory))
            if tab.get("color"):
                profile.set_use_tab_color(True)
                profile.set_tab_color(hex_to_color(tab["color"]))
            return profile


        async def open_tab(connection, app, window, tab):
            panes = tab["panes"]
            first = customizations(tab, panes[0])
            if window is None:
                window = await iterm2.Window.async_create(connection, profile_customizations=first)
                if window is None:
                    raise RuntimeError("iTerm could not create a window")
                itab = window.current_tab
            else:
                itab = await window.async_create_tab(profile_customizations=first)

            sessions = [itab.current_session]
            for pane in panes[1:]:
                parent = sessions[pane["parent"]]
                sessions.append(await parent.async_split_pane(
                    vertical=pane["vertical"],
                    profile_customizations=customizations(tab, pane)))

            for pane, session in zip(panes, sessions):
                if pane.get("name"):
                    await session.async_set_name(pane["name"])
                if pane.get("command"):
                    await session.async_send_text(pane["command"] + "\\n")
            if tab.get("title"):
                await itab.async_set_title(tab["title"])
            await sessions[0].async_activate()
            return window


        def to_frame(f):
            return iterm2.Frame(iterm2.Point(int(f["x"]), int(f["y"])),
                                iterm2.Size(int(f["width"]), int(f["height"])))


        async def main(connection):
            app = await iterm2.async_get_app(connection)
            for i, spec in enumerate(PRESET["windows"]):
                # Only the first window may reuse the current one; it is never moved or resized.
                reuse = i == 0 and PRESET["target"] == "currentWindow"
                window = app.current_terminal_window if reuse else None
                created = window is None
                for n, tab in enumerate(spec["tabs"]):
                    window = await open_tab(connection, app, window, tab)
                    if n == 0 and created and spec.get("frame"):
                        await window.async_set_frame(to_frame(spec["frame"]))
                if window is not None:
                    await window.async_activate()


        iterm2.run_until_complete(main)

        """
    }

    /// File name used inside iTerm's Scripts folder.
    static func fileName(for preset: Preset) -> String {
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "-_ "))
        var name = String(preset.name.unicodeScalars.map { allowed.contains($0) ? Character($0) : "-" })
            .trimmingCharacters(in: .whitespaces)
        if name.isEmpty { name = "Preset" }
        return name + ".py"
    }
}

/// The flattened shape the Python runner reads.
private struct PresetPayload: Encodable {
    struct Tab: Encodable {
        let title: String
        let color: String?
        let directory: String
        let panes: [Pane]
    }
    struct Pane: Encodable {
        let name: String
        let directory: String
        let command: String
        let parent: Int
        /// iTerm's `vertical=True` means a vertical divider, i.e. the new pane goes to the right.
        let vertical: Bool
    }

    struct Window: Encodable {
        let frame: WindowFrame?
        let tabs: [Tab]
    }

    let name: String
    let target: String
    let windows: [Window]

    init(_ preset: Preset) {
        name = preset.name
        target = preset.target.rawValue
        windows = preset.windows.enumerated().map { i, window in
            Window(frame: preset.reusesCurrentWindow(i) ? nil : window.frame,
                   tabs: window.tabs.map { tab in
                       Tab(title: tab.title, color: tab.colorHex, directory: tab.directory,
                           panes: Self.flatten(tab.layout))
                   })
        }
    }

    /// Turns the split tree into the runner's ordered list: entry 0 is the tab's first session,
    /// and every later entry is made by splitting the earlier session at `parent`. A split is
    /// emitted while its session still covers exactly the split's region, so halves come out right.
    static func flatten(_ layout: PaneNode) -> [Pane] {
        var parents = [(parent: 0, vertical: true)]
        var panes: [Int: PaneSpec] = [:]
        func walk(_ node: PaneNode, session: Int) {
            switch node {
            case .pane(let pane):
                panes[session] = pane
            case .split(let direction, let first, let second):
                parents.append((session, direction == .right))
                let created = parents.count - 1
                walk(first, session: session)
                walk(second, session: created)
            }
        }
        walk(layout, session: 0)
        return parents.indices.map { i in
            let pane = panes[i] ?? PaneSpec()
            return Pane(name: pane.name, directory: pane.directory, command: pane.command,
                        parent: parents[i].parent, vertical: parents[i].vertical)
        }
    }
}
